// Draws `txt` with the vector font. align: -1 right, 0 center, 1 left.
// Side effect: translates the context (so text can follow).
function font(txt, fontSize, align, lineWidth) {
  var l = fontSize * 11 * txt.length;
  ctx.translate(align ? (align > 0 ? 0 : -l) : -l / 2, 0);
  for (var i = 0; i < txt.length; i++) {
    var glyph = FONT[txt[i]];
    if (glyph) {
      path(glyph.map(function (o) {
        return o && [4 * fontSize * o[0], 5 * fontSize * o[1]];
      }), 1);
      ctx.lineWidth = lineWidth || 1;
      ctx.lineJoin = "miter";
      ctx.stroke();
    }
    ctx.translate(fontSize * 11, 0);
  }
}

function path(pts, noclose) {
  ctx.beginPath();
  var mv = 1;
  for (var i = 0; pts && i < pts.length; ++i) {
    var p = pts[i];
    if (p) {
      if (mv) ctx.moveTo(p[0], p[1]);
      else ctx.lineTo(p[0], p[1]);
      mv = 0;
    } else mv = 1;
  }
  if (!noclose) ctx.closePath();
}

